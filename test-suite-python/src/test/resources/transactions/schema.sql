CREATE TABLE IF NOT EXISTS horses(name VARCHAR(255) PRIMARY KEY, age INT);
CREATE TABLE IF NOT EXISTS audit(message VARCHAR(255) NOT NULL);
CREATE TABLE IF NOT EXISTS orders(id VARCHAR(255) NOT NULL);
CREATE TABLE IF NOT EXISTS aggregation(id VARCHAR(255) NOT NULL PRIMARY KEY, exchange BLOB NOT NULL, version BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS aggregation_completed(id VARCHAR(255) NOT NULL PRIMARY KEY, exchange BLOB NOT NULL, version BIGINT NOT NULL);
