package io.micronaut.camel.graal;

import org.junit.jupiter.api.Test;

import java.io.ByteArrayInputStream;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.util.LinkedHashSet;
import java.util.Set;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNull;

class CamelNativeFeatureTest {

    @Test
    void readsTheClassOfACamelServiceFile() throws IOException {
        Set<String> reflective = new LinkedHashSet<>();
        Set<String> proxies = new LinkedHashSet<>();

        read("META-INF/services/org/apache/camel/component/timer", """
            # Generated by camel build tools - do NOT edit this file!
            class=org.apache.camel.component.timer.TimerComponent
            """, reflective, proxies);

        assertEquals(Set.of("org.apache.camel.component.timer.TimerComponent"), reflective);
        assertEquals(Set.of(), proxies);
    }

    @Test
    void readsTheTypeConverterLoaders() throws IOException {
        Set<String> reflective = new LinkedHashSet<>();

        read("META-INF/services/org/apache/camel/TypeConverterLoader", """
            # Generated by camel build tools - do NOT edit this file!
            org.apache.camel.converter.CamelBaseBulkConverterLoader
            """, reflective, new LinkedHashSet<>());

        assertEquals(Set.of("org.apache.camel.converter.CamelBaseBulkConverterLoader"), reflective);
    }

    @Test
    void readsTheMetadataOfTheAnnotationProcessor() throws IOException {
        Set<String> reflective = new LinkedHashSet<>();
        Set<String> proxies = new LinkedHashSet<>();

        read("META-INF/micronaut-camel/native/example.Shop", """
            proxy=example.Orders
            reflect=example.Shop
            """, reflective, proxies);

        assertEquals(Set.of("example.Shop"), reflective);
        assertEquals(Set.of("example.Orders"), proxies);
    }

    @Test
    void namesThePropertiesOfGetters() {
        assertEquals("jdbcUrl", CamelNativeFeature.propertyName("getJdbcUrl"));
        assertEquals("URL", CamelNativeFeature.propertyName("getURL"));
        assertEquals("closed", CamelNativeFeature.propertyName("isClosed"));
        assertNull(CamelNativeFeature.propertyName("get"));
        assertNull(CamelNativeFeature.propertyName("close"));
    }

    private static void read(String name, String content, Set<String> reflective, Set<String> proxies) throws IOException {
        CamelNativeFeature.read(name, new ByteArrayInputStream(content.getBytes(StandardCharsets.UTF_8)), reflective, proxies);
    }
}
